# Crew Roll transformations for Pokémon: every Pokémon with a Mega Evolution, a Primal Reversion or a Gigantamax form
# (PokeAPI's data, https://github.com/PokeAPI/pokeapi) gets it as its transformation, with its official artwork, for the
# card's neon and aura, the showcase and the cinematic. One form per Pokémon: the Mega (X first), else Primal, else Gigantamax.
# Writes the pictures to crew/assets/forms/pokemon-<id>.webp (+ sm/) and the block between the markers in crew/forms.js.
# Usage: python pokemon/scripts/forms.py   (needs Pillow)
import csv, io, json, os, re, urllib.request
from concurrent.futures import ThreadPoolExecutor
from PIL import Image

ROOT = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
CSV = "https://raw.githubusercontent.com/PokeAPI/pokeapi/master/data/v2/csv/{}.csv"
ART = "https://raw.githubusercontent.com/PokeAPI/sprites/master/sprites/pokemon/other/official-artwork/{}.png"
EN, FR = 9, 5
# Colour of each type (c1), and a dark shade of it (c2).
TYPE_RGB = {1: (200, 200, 180), 2: (230, 80, 50), 3: (150, 190, 255), 4: (190, 90, 220), 5: (220, 180, 90), 6: (190, 160, 90),
            7: (170, 200, 40), 8: (130, 100, 220), 9: (170, 190, 210), 10: (255, 120, 40), 11: (60, 150, 255), 12: (90, 210, 90),
            13: (255, 220, 50), 14: (255, 90, 160), 15: (130, 220, 255), 16: (110, 90, 255), 17: (110, 90, 80), 18: (255, 150, 220)}
KIND = {
    "mega": ({"en": "Mega {}", "fr": "Méga-{}"}, "aura", "メガシンカ"),
    "primal": ({"en": "Primal {}", "fr": "Primo-{}"}, "domain", "ゲンシカイキ"),
    "gmax": ({"en": "Gigantamax {}", "fr": "{} Gigamax"}, "pillar", "キョダイマックス"),
}


def table(name):
    with urllib.request.urlopen(CSV.format(name)) as r:
        return list(csv.DictReader(io.TextIOWrapper(r, encoding="utf-8")))


species = {int(s["id"]): s for s in table("pokemon_species")}
names = {(int(n["pokemon_species_id"]), int(n["local_language_id"])): n["name"] for n in table("pokemon_species_names")}
types = {}
for t in sorted(table("pokemon_types"), key=lambda t: int(t["slot"])):
    types.setdefault(int(t["pokemon_id"]), []).append(int(t["type_id"]))

slug = lambda s: re.sub(r"[^a-z0-9]+", "-", s.lower()).strip("-")
forms = {}
for p in table("pokemon"):
    ident, sid = p["identifier"], int(p["species_id"])
    m = re.search(r"-(mega)(?:-([xy]))?$|-(primal)$|-(gmax)$", ident)
    if not m or sid > 1025: continue
    kind = m.group(1) or m.group(3) or m.group(4)
    rank = {"mega": 0, "primal": 1, "gmax": 2}[kind] + (0.5 if m.group(2) == "y" else 0)
    cid = slug(species[sid]["identifier"])
    if cid in forms and forms[cid]["rank"] <= rank: continue
    suffix = f" {m.group(2).upper()}" if m.group(2) else ""
    label, fx, kanji = KIND[kind]
    t = types.get(int(p["id"])) or types[sid]
    c1 = TYPE_RGB[t[0]]
    c2 = tuple(int(v * 0.25) for v in TYPE_RGB[t[1] if len(t) > 1 else t[0]])
    forms[cid] = {"rank": rank, "pid": int(p["id"]), "name": {"en": label["en"].format(names[(sid, EN)]) + suffix, "fr": label["fr"].format(names[(sid, FR)]) + suffix},
                  "fx": fx, "c1": ", ".join(map(str, c1)), "c2": ", ".join(map(str, c2)), "kanji": kanji}

out = os.path.join(ROOT, "crew", "assets", "forms")


def picture(item):
    cid, f = item
    path = os.path.join(out, f"pokemon-{cid}.webp")
    if os.path.exists(path): return cid, True
    try:
        with urllib.request.urlopen(ART.format(f["pid"])) as r:
            im = Image.open(io.BytesIO(r.read())).convert("RGBA")
    except Exception:
        return cid, False
    im = im.crop(im.getbbox() or (0, 0, im.width, im.height))
    side = max(im.size)
    sq = Image.new("RGBA", (side, side), (0, 0, 0, 0))
    sq.paste(im, ((side - im.width) // 2, (side - im.height) // 2))
    sq.resize((320, 320), Image.LANCZOS).save(path, quality=84, method=6)
    sq.resize((160, 160), Image.LANCZOS).save(os.path.join(out, "sm", f"pokemon-{cid}.webp"), quality=80, method=6)
    return cid, True


with ThreadPoolExecutor(12) as pool:
    ok = dict(pool.map(picture, forms.items()))
missing = [c for c, good in ok.items() if not good]
for c in missing: del forms[c]

lines = [f'      {json.dumps(cid)}: {{ arc: 0, name: {{ en: {json.dumps(f["name"]["en"], ensure_ascii=False)}, fr: {json.dumps(f["name"]["fr"], ensure_ascii=False)} }}, '
         f'fx: "{f["fx"]}", c1: "{f["c1"]}", c2: "{f["c2"]}", kanji: "{f["kanji"]}", lightning: true }},' for cid, f in sorted(forms.items(), key=lambda x: x[1]["pid"])]
block = "  // <pokemon-forms> generated by pokemon/scripts/forms.py: Mega Evolutions, Primal Reversions and Gigantamax forms.\n" \
        "  window.CREW_FORMS.pokemon = {\n" + "\n".join(lines) + "\n  };\n  // </pokemon-forms>\n"
fj = os.path.join(ROOT, "crew", "forms.js")
s = open(fj, encoding="utf-8").read()
if "// <pokemon-forms>" in s:
    s = re.sub(r"  // <pokemon-forms>.*?// </pokemon-forms>\n", lambda _: block, s, flags=re.S)
else:
    anchor = "\n  // Forms with an anime clip"
    assert anchor in s
    s = s.replace(anchor, "\n" + block + anchor, 1)
open(fj, "w", encoding="utf-8", newline="").write(s)
print(len(forms), "forms;", "no picture:", missing)
