// Language is shared by every category.
window.DLE_LANG = {
  get() {
    try {
      const v = localStorage.getItem("dle:lang");
      if (v === "en" || v === "fr") return v;
    } catch {}
    return (navigator.language || "").startsWith("fr") ? "fr" : "en";
  },
  set(lang) {
    try {
      localStorage.setItem("dle:lang", lang);
    } catch {}
  },
};
